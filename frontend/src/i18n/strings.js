export function detectLang() {
  try {
    const stored = localStorage.getItem("frt_lang");
    if (stored && STRINGS[stored]) return { lang: stored, source: "stored" };
    const tag    = (navigator.language || "es").toLowerCase();
    const base   = tag.split("-")[0];
    const region = (tag.split("-")[1] || "").toUpperCase();
    if (region && COUNTRY_LANG[region]) return { lang: COUNTRY_LANG[region], source: "region" };
    if (STRINGS[base]) return { lang: base, source: "language" };
  } catch (_) {}
  return { lang: "es", source: "default" };
}

